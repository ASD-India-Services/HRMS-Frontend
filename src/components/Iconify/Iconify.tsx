export type IconName = keyof typeof ICONS;

interface IconifyProps {
  icon: IconName;
  className?: string;
  width?: number | string;
}

export function isIconName(name: string): name is IconName {
  return Object.prototype.hasOwnProperty.call(ICONS, name);
}

export function Iconify({ icon, className, width = 20 }: IconifyProps) {
  return <Icon icon={ICONS[icon]} width={width} height={width} className={className} aria-hidden="true" />;
}
